-- ROW_ID 是本轮新加的：主键必选（所有者 2026-08-18 裁定），B2 原本一列可做主键的都没有。
-- 它映射干净、不产生任何预检问题，B2 数出来的问题数因此只反映那些真正被拒的列。
CREATE TABLE M3_B2 (
  ROW_ID       DECIMAL(8,0) NOT NULL,
  BF           DOUBLE NULL,
  BD           DOUBLE NULL,
  PAYLOAD      TEXT NULL,
  C_CHAR       CHAR(10) NULL,
  N_TOO_WIDE   DECIMAL(65,0) NULL,
  N_TOO_SCALE  DECIMAL(35,30) NULL,
  D_WRONG      VARCHAR(30) NULL,
  LOAD_DATE    DATETIME(0) NULL,
  -- EXTRA 未被映射且可空：ADR-0038 §4 把「列名集合完全相等」撤成子集判定之后，
  -- 它**不再**产生 `源端结果缺少同名列`。B2 就地反过来断言它一条问题都不出。
  EXTRA        VARCHAR(10) NULL,
  PRIMARY KEY (ROW_ID),
  KEY IDX_M3_B2_LOAD_DATE (LOAD_DATE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

