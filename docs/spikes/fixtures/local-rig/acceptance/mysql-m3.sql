-- 写入模型是 upsert（ADR-0035 §1）：目标表必须真有一条列集合与勾选主键一致的
-- PRIMARY KEY / UNIQUE，否则 `ON DUPLICATE KEY UPDATE` 静默退化成纯 INSERT。
-- 六张 B 表因此都补上 PRIMARY KEY，主键列一并改成 NOT NULL。
CREATE TABLE M3_B1 (
  ROW_ID     DECIMAL(8,0) NOT NULL,
  N_REGULAR  DECIMAL(38,2) NULL,
  N_FRACTION DECIMAL(6,6) NULL,
  N_NEGATIVE DECIMAL(10,0) NULL,
  N_BARE     DECIMAL(20,4) NULL,
  -- V_TEXT / C_TEXT 建 40 而非 10：源 VARCHAR2(10 CHAR) / CHAR(10 CHAR) 的 describe
  -- 长度由驱动按「字节」给出（AL32UTF8 下 = 40），而判定式 n' >= n 按字符比。
  -- 第一版认下这份过严，见 ADR-0033。NV_TEXT / NC_TEXT 的 N 族驱动直接给字符数，仍是 10。
  V_TEXT     VARCHAR(40) NULL,
  NV_TEXT    VARCHAR(10) NULL,
  C_TEXT     VARCHAR(40) NULL,
  NC_TEXT    VARCHAR(10) NULL,
  D_VALUE    DATETIME(0) NULL,
  TS0        DATETIME(6) NULL,
  TS3        DATETIME(6) NULL,
  TS6        DATETIME(6) NULL,
  LOAD_DATE  DATETIME(0) NULL,
  PRIMARY KEY (ROW_ID),
  KEY IDX_M3_B1_LOAD_DATE (LOAD_DATE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

