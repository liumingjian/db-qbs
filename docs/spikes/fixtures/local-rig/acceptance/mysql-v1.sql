USE qbs;

-- 第一版验收（C1-C6）的目标端 fixture —— ADR-0040 §4。
--
-- **另起文件，不改 mysql.sql**：M1_NARROW / M1_WIDE 是常量基线（ADR-0040 §1）。
-- C6 的宽表目标端因此也另起一张 V1_WIDE，形状与 M1_WIDE 一致但互不干扰——
-- C6 会往里灌 10 万行并留在那儿，压到 M1_WIDE 上会让下一份 M1 台架读到别人的残留。

DROP TABLE IF EXISTS V1_C2;
DROP TABLE IF EXISTS V1_C3;
DROP TABLE IF EXISTS V1_C4;
DROP TABLE IF EXISTS V1_C4_NOPK;
DROP TABLE IF EXISTS V1_C5_NULLABLE_PK;
DROP TABLE IF EXISTS V1_C5_PASS;
DROP TABLE IF EXISTS V1_C5_REQUIRED;
DROP TABLE IF EXISTS V1_WIDE;

-- C2：列名与源端**不同**（SRC_NAME → DEST_NAME、SRC_AMOUNT → DEST_AMOUNT）。
-- 跑通后按目标名核对数据，证明 `a.SRC_NAME AS DEST_NAME` 那条投影是真的落到了目标列上。
CREATE TABLE V1_C2 (
  ROW_ID      DECIMAL(8,0) NOT NULL,
  DEST_NAME   VARCHAR(80) NULL,
  DEST_AMOUNT DECIMAL(10,2) NULL,
  LOAD_DATE   DATETIME(0) NULL,
  PRIMARY KEY (ROW_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE V1_C3 (
  ROW_ID    DECIMAL(8,0) NOT NULL,
  GRP       VARCHAR(16) NULL,
  LOAD_DATE DATETIME(0) NULL,
  PRIMARY KEY (ROW_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE V1_C4 (
  ROW_ID    DECIMAL(8,0) NOT NULL,
  V_TEXT    VARCHAR(80) NULL,
  LOAD_DATE DATETIME(0) NULL,
  PRIMARY KEY (ROW_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- C4 ⑤：目标表缺 PK/UNIQUE → 预检拒跑。ROW_ID 仍是 NOT NULL，**唯一缺的就是那条约束**——
-- 缺别的东西也会被拒，那样这条用例证不到「缺唯一约束」这一件事（ADR-0035 §2 第 2 条）。
CREATE TABLE V1_C4_NOPK (
  ROW_ID    DECIMAL(8,0) NOT NULL,
  V_TEXT    VARCHAR(80) NULL,
  LOAD_DATE DATETIME(0) NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- C5 ①：被映射到的主键列在目标端**可空** → 拒。
-- MySQL 的 PRIMARY KEY 按定义强制 NOT NULL，所以这一档只能用 UNIQUE 造出来——
-- 而这恰好就是它要防的那个失效模式：UNIQUE 允许多个 NULL，upsert 会静默退化成纯 INSERT。
CREATE TABLE V1_C5_NULLABLE_PK (
  ROW_ID    DECIMAL(8,0) NULL,
  V_TEXT    VARCHAR(80) NULL,
  LOAD_DATE DATETIME(0) NULL,
  UNIQUE KEY UK_V1_C5_NULLABLE_PK (ROW_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- C5 ②：被映射到的非主键列可空 → 放行。顺带把「未映射但有默认值的审计列」一并摆进来：
-- CREATE_TIME 是 NOT NULL 但有 DEFAULT CURRENT_TIMESTAMP，按 ADR-0038 §5 第 3 分支放行。
-- 一次跑通同时证两条放行，比分两张表更省一趟 100 行的搬运。
CREATE TABLE V1_C5_PASS (
  ROW_ID      DECIMAL(8,0) NOT NULL,
  V_TEXT      VARCHAR(80) NULL,
  LOAD_DATE   DATETIME(0) NULL,
  CREATE_TIME DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (ROW_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- C5 ③：未映射列既非空、又无 COLUMN_DEFAULT、又非 auto_increment → 拒。
-- 不拒的话它会搬到一半撞 ERROR 1364，那时暂存表已经写了一半。
CREATE TABLE V1_C5_REQUIRED (
  ROW_ID    DECIMAL(8,0) NOT NULL,
  V_TEXT    VARCHAR(80) NULL,
  LOAD_DATE DATETIME(0) NULL,
  MUST_FILL VARCHAR(20) NOT NULL,
  PRIMARY KEY (ROW_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- C6：宽表目标端，与 M1_WIDE 同形（68 列 VARCHAR(96) + ROW_ID + D_BIZ）。
-- 列宽为什么是 96 不是 48，见 mysql.sql 里那段 InnoDB 行长上限的注释——同一条约束。
DELIMITER //
DROP PROCEDURE IF EXISTS create_v1_wide//
CREATE PROCEDURE create_v1_wide()
BEGIN
  DECLARE i INT DEFAULT 1;
  SET @ddl = 'CREATE TABLE V1_WIDE (ROW_ID DECIMAL(8,0) NOT NULL, D_BIZ DATETIME(0) NULL';
  WHILE i <= 68 DO
    SET @ddl = CONCAT(@ddl, ', C', LPAD(i, 2, '0'), ' VARCHAR(96) NULL');
    SET i = i + 1;
  END WHILE;
  SET @ddl = CONCAT(@ddl, ', PRIMARY KEY (ROW_ID)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4');
  PREPARE statement FROM @ddl;
  EXECUTE statement;
  DEALLOCATE PREPARE statement;
END//
DELIMITER ;
CALL create_v1_wide();
DROP PROCEDURE create_v1_wide;
