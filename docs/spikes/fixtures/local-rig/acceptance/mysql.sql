USE qbs;
DROP TABLE IF EXISTS M1_NARROW;
DROP TABLE IF EXISTS M1_WIDE;

CREATE TABLE M1_NARROW (
  ROW_ID DECIMAL(8,0) NULL,
  V_TEXT VARCHAR(200) NULL,
  D_BIZ DATETIME(0) NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

DELIMITER //
DROP PROCEDURE IF EXISTS create_m1_wide//
CREATE PROCEDURE create_m1_wide()
BEGIN
  DECLARE i INT DEFAULT 1;
  SET @ddl = 'CREATE TABLE M1_WIDE (ROW_ID DECIMAL(8,0) NULL, D_BIZ DATETIME(0) NULL';
  WHILE i <= 68 DO
    SET @ddl = CONCAT(@ddl, ', C', LPAD(i, 2, '0'), ' VARCHAR(48) NULL');
    SET i = i + 1;
  END WHILE;
  SET @ddl = CONCAT(@ddl, ') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4');
  PREPARE statement FROM @ddl;
  EXECUTE statement;
  DEALLOCATE PREPARE statement;
END//
DELIMITER ;
CALL create_m1_wide();
DROP PROCEDURE create_m1_wide;
