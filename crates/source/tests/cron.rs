//! 五字段 cron 解析器的**语义钉子**（#265）。
//!
//! 这个模块之所以是手写的，理由写在 `crates/source/src/cron.rs` 的模块头上；而手写的代价
//! 就得由这一份表格来付：它不是「覆盖率」，它是这门语言在本产品里的**定义**。每一行都是
//! 一句可以拿去和人对账的话——「这个表达式，在这个时刻，下一次是那个时刻」。
//!
//! 表里刻意压着四类边界：**月末**（31 号在只有 30 天的月份里怎么跳）、**跨年**、
//! **`*/n` 的取整**（余数不为零时往上翻一格，而不是从当前值起步），以及**无效表达式的拒绝**。
//! 第四类同样按时刻对账的方式列出来：错误消息是给人看的，它和触发时刻一样是产品的一部分。

use chrono::{NaiveDate, NaiveDateTime};
use db_qbs_source::CronSchedule;

fn at(year: i32, month: u32, day: u32, hour: u32, minute: u32) -> NaiveDateTime {
    NaiveDate::from_ymd_opt(year, month, day)
        .unwrap()
        .and_hms_opt(hour, minute, 0)
        .unwrap()
}

/// 表达式、起点、下一次触发。**这张表就是语义本身。**
#[test]
fn the_next_fire_time_is_pinned_case_by_case() {
    let cases: &[(&str, NaiveDateTime, NaiveDateTime)] = &[
        // ── 最朴素的一档：每分钟。严格晚于起点，所以同一分钟不会被交回来。
        ("* * * * *", at(2026, 8, 28, 10, 7), at(2026, 8, 28, 10, 8)),
        // ── 「凌晨两点」。落在 02:00 那一刻问下一次，答案是明天，不是原地。
        ("0 2 * * *", at(2026, 8, 28, 1, 59), at(2026, 8, 28, 2, 0)),
        ("0 2 * * *", at(2026, 8, 28, 2, 0), at(2026, 8, 29, 2, 0)),
        // ── `*/n` 的取整：从**整点起算**的格子，不是从当前时刻起算的间隔。
        ("*/15 * * * *", at(2026, 8, 28, 10, 7), at(2026, 8, 28, 10, 15)),
        ("*/15 * * * *", at(2026, 8, 28, 10, 15), at(2026, 8, 28, 10, 30)),
        // 41 分越过了这一小时最后一格（40），于是翻到下一个整点——不是 10:61。
        ("*/20 * * * *", at(2026, 8, 28, 10, 41), at(2026, 8, 28, 11, 0)),
        // 60 不被 25 整除：最后一格是 50，之后直接翻格。这是取整最容易被写错的一种。
        ("*/25 * * * *", at(2026, 8, 28, 10, 51), at(2026, 8, 28, 11, 0)),
        ("0 */5 * * *", at(2026, 8, 28, 7, 30), at(2026, 8, 28, 10, 0)),
        // 一天的最后一格之后翻到第二天。
        ("0 */5 * * *", at(2026, 8, 28, 20, 1), at(2026, 8, 29, 0, 0)),
        // 带区间的步长：`8-18/2` 只在工作时段里每两小时一次。
        ("0 8-18/2 * * *", at(2026, 8, 28, 9, 30), at(2026, 8, 28, 10, 0)),
        ("0 8-18/2 * * *", at(2026, 8, 28, 18, 30), at(2026, 8, 29, 8, 0)),
        // ── 并列与区间。
        ("0 9,18 * * *", at(2026, 8, 28, 12, 0), at(2026, 8, 28, 18, 0)),
        ("30 9-11 * * *", at(2026, 8, 28, 10, 45), at(2026, 8, 28, 11, 30)),
        ("30 9-11 * * *", at(2026, 8, 28, 11, 45), at(2026, 8, 29, 9, 30)),
        // ── 月末：31 号在 30 天的月份里不存在，直接跳过整个月。
        ("30 23 31 * *", at(2026, 4, 1, 0, 0), at(2026, 5, 31, 23, 30)),
        ("0 0 31 * *", at(2026, 1, 31, 0, 1), at(2026, 3, 31, 0, 0)),
        // 月初：从月末的最后一分钟迈进下个月。
        ("0 0 1 * *", at(2026, 1, 31, 23, 59), at(2026, 2, 1, 0, 0)),
        // 2 月只有 28 天（2026 不是闰年），29/30/31 在这个月都不存在。
        ("0 0 29 * *", at(2026, 2, 1, 0, 0), at(2026, 3, 29, 0, 0)),
        // ── 跨年。
        ("0 0 1 1 *", at(2026, 6, 15, 12, 0), at(2027, 1, 1, 0, 0)),
        ("59 23 31 12 *", at(2026, 12, 31, 23, 58), at(2026, 12, 31, 23, 59)),
        ("59 23 31 12 *", at(2026, 12, 31, 23, 59), at(2027, 12, 31, 23, 59)),
        // 闰日：2 月 29 号要等到下一个闰年，跨的是**两年**而不是一年。
        ("0 0 29 2 *", at(2026, 3, 1, 0, 0), at(2028, 2, 29, 0, 0)),
        ("0 0 29 2 *", at(2028, 2, 29, 0, 1), at(2032, 2, 29, 0, 0)),
        // ── 星期。2026-08-28 是周五。
        ("0 9 * * 1", at(2026, 8, 28, 9, 0), at(2026, 8, 31, 9, 0)),
        // 0 与 7 都是周日，两种写法必须给出同一个答案。
        ("0 0 * * 0", at(2026, 8, 28, 0, 0), at(2026, 8, 30, 0, 0)),
        ("0 0 * * 7", at(2026, 8, 28, 0, 0), at(2026, 8, 30, 0, 0)),
        ("0 8 * * 1-5", at(2026, 8, 28, 9, 0), at(2026, 8, 31, 8, 0)),
        // ── 「日」与「周」同时被限定时是**或**，不是且（Vixie cron 的老规矩）。
        // 8 月 31 号恰好是周一，但下面这条在 8 月 30 号（周日）就该响。
        ("0 0 1 * 0", at(2026, 8, 28, 0, 0), at(2026, 8, 30, 0, 0)),
        // 同一条表达式在下一个周日之前先撞上 9 月 1 号。
        ("0 0 1 * 0", at(2026, 8, 30, 0, 1), at(2026, 9, 1, 0, 0)),
        // 只限定「日」时，星期一概不管。
        ("0 0 15 * *", at(2026, 8, 28, 0, 0), at(2026, 9, 15, 0, 0)),
        // ── 空白宽容：多个空格、制表符、首尾空白都不该是错。
        ("  0   2  *  *  * ", at(2026, 8, 28, 2, 0), at(2026, 8, 29, 2, 0)),
        ("0\t2\t*\t*\t*", at(2026, 8, 28, 2, 0), at(2026, 8, 29, 2, 0)),
    ];

    for (expression, from, expected) in cases {
        let schedule = CronSchedule::parse(expression)
            .unwrap_or_else(|error| panic!("{expression} 应当解析成功，却被拒：{error}"));
        assert_eq!(
            schedule.next_after(*from),
            Some(*expected),
            "{expression} 从 {from} 起的下一次触发不对"
        );
    }
}

/// 表达式合法、但它指的那个时刻在日历上根本不存在。
///
/// 这不是解析错误——`0 0 30 2 *` 每一个字段都在取值范围里。它是一个**永远不会响的闹钟**，
/// 而永远不响必须被说成「没有下一次」，不能被凑成某个看起来像那么回事的时刻。
#[test]
fn an_expression_that_can_never_fire_has_no_next_time() {
    let schedule = CronSchedule::parse("0 0 30 2 *").unwrap();
    assert_eq!(schedule.next_after(at(2026, 1, 1, 0, 0)), None);
    assert!(schedule.upcoming(at(2026, 1, 1, 0, 0), 5).is_empty());
}

/// 表达式、被拒的理由。**错误消息是产品的一部分**：它会原样出现在保存被拒时的提示上，
/// 所以它在这里被钉住，和触发时刻同等待遇。
#[test]
fn an_invalid_expression_is_refused_with_a_readable_reason() {
    let cases: &[(&str, &str)] = &[
        ("", "cron 表达式不能为空"),
        ("   ", "cron 表达式不能为空"),
        ("* * * *", "cron 表达式要五个字段（分 时 日 月 周），这里有 4 个：* * * *"),
        (
            "* * * * * *",
            "cron 表达式要五个字段（分 时 日 月 周），这里有 6 个：* * * * * *",
        ),
        ("60 * * * *", "分钟字段的 60 超出取值范围 0-59"),
        ("0 24 * * *", "小时字段的 24 超出取值范围 0-23"),
        ("0 0 0 * *", "日字段的 0 超出取值范围 1-31"),
        ("0 0 32 * *", "日字段的 32 超出取值范围 1-31"),
        ("0 0 * 13 *", "月字段的 13 超出取值范围 1-12"),
        ("0 0 * * 8", "星期字段的 8 超出取值范围 0-7"),
        ("*/0 * * * *", "分钟字段的步长要大于 0：*/0"),
        ("30-10 * * * *", "分钟字段的区间起点比终点大：30-10"),
        (
            "5/10 * * * *",
            "分钟字段的步长只能跟在 * 或 a-b 后面：5/10",
        ),
        (
            "MON * * * *",
            "分钟字段看不懂这一项：MON（只支持 *、a、a-b、*/n、a-b/n，以及用逗号并列）",
        ),
        (
            "0 0 * * MON",
            "星期字段看不懂这一项：MON（只支持 *、a、a-b、*/n、a-b/n，以及用逗号并列）",
        ),
        (
            "0,,30 * * * *",
            "分钟字段看不懂这一项：（只支持 *、a、a-b、*/n、a-b/n，以及用逗号并列）",
        ),
        (
            "-5 * * * *",
            "分钟字段看不懂这一项：-5（只支持 *、a、a-b、*/n、a-b/n，以及用逗号并列）",
        ),
        (
            "0 0 1 * * ; rm -rf /",
            "cron 表达式要五个字段（分 时 日 月 周），这里有 9 个：0 0 1 * * ; rm -rf /",
        ),
    ];

    for (expression, reason) in cases {
        assert_eq!(
            CronSchedule::parse(expression),
            Err((*reason).to_owned()),
            "{expression} 被拒的理由不对"
        );
    }
}

/// 接下来的几次，而不只是下一次。
///
/// 界面上一次给一串，是因为 `*/n` 的取整只看一个数字说不清——「10:15」看不出来它是每
/// 十五分钟还是每小时一次，「10:15、10:30、10:45」一眼就够了。
#[test]
fn the_upcoming_list_is_the_next_times_in_order() {
    let schedule = CronSchedule::parse("*/15 * * * *").unwrap();
    assert_eq!(
        schedule.upcoming(at(2026, 8, 28, 10, 7), 3),
        vec![
            at(2026, 8, 28, 10, 15),
            at(2026, 8, 28, 10, 30),
            at(2026, 8, 28, 10, 45),
        ]
    );
}

/// 它是**纯函数**：同一个表达式、同一个时刻，问多少遍都是同一个答案，中间不读表、
/// 不看时区、不碰任何存储。#266 的调度器会拿上一次的触发时刻回来问下一次，
/// 那条循环的正确性完全建立在这一条上。
#[test]
fn the_parser_is_a_pure_function_of_expression_and_instant() {
    let schedule = CronSchedule::parse("0 2 * * *").unwrap();
    let from = at(2026, 8, 28, 3, 0);
    let once = schedule.next_after(from);
    assert_eq!(once, schedule.next_after(from));
    assert_eq!(once, CronSchedule::parse("0 2 * * *").unwrap().next_after(from));
    // 起点的秒与纳秒不参与判断：cron 的分辨率就是分钟。
    let with_seconds = NaiveDate::from_ymd_opt(2026, 8, 28)
        .unwrap()
        .and_hms_milli_opt(3, 0, 59, 999)
        .unwrap();
    assert_eq!(schedule.next_after(with_seconds), once);
}
